import json, numpy as np, sciris as sc, starsim as ss
def show(f):
    try: r = f(); print('NO ERROR', '' if r is None else str(r)[:300], '\n')
    except Exception as e: print(f'[{type(e).__name__}] {str(e)[:400]}\n')
print('--- E604 at run: par(None) ---')
S, I, R = ss.states(3)
show(lambda: ss.Sim(ss.Disease(S >> I @ ss.par(None, name='beta') * I, I >> R @ 10, name='x'), verbose=0, total_pop=1000, stop=20).run())
print('--- notes recorded vs verbose ---')
def mk(v):
    S, I, R = ss.states(3)
    s = ss.Sim(ss.Disease(S >> I @ 0.05 * I, I >> R @ ss.lognorm_ex(10, 3, unit='days'), name='sir'), verbose=v, total_pop=1000, start='2020-01-01', stop='2020-07-01'); s.init(); return s
s0, s1 = mk(0), mk(1)
print('verbose=0 notes:', s0.notes); print('verbose=1 notes:', s1.notes)
print('meta.notes equal:', s0.to_spec()['meta']['notes'] == s1.to_spec()['meta']['notes'])
print('hash equal:', s0.hash() == s1.hash())
print('--- where= and a lazy condition in the spec ---')
S, I, R = ss.states(3)
sir = ss.Disease(S >> I @ 0.05 * I, I >> R @ ss.days(10), name='sir')
sim = ss.Sim(sir, people=ss.People(1), verbose=0, total_pop=1000, start='2020-01-01', stop='2020-07-01')
try:
    sim.stratify(sex=['f', 'm']); sim.stratify(parity=[0, 1, 2], where=lambda ppl: ppl.sex == 'f')
    sim.init(); st = sim.to_spec()['stratify']; print(json.dumps(st)[:600])
except Exception as e: print('stratify where failed:', type(e).__name__, str(e)[:300])
print('--- an ABM sim with RandomNet: network entry in spec ---')
S, I, R = ss.states(3)
sir = ss.Disease(S >> I @ 0.05 * I, I >> R @ ss.days(10), name='sir')
sim = ss.Sim(sir, networks='random', n_agents=500, verbose=0, start='2020-01-01', stop='2020-03-01'); sim.init()
sp = sim.to_spec(); print(json.dumps(sp['networks'])[:700]); print('config:', sp['config'])
h0 = sim.hash(); sim.run(); print('hash stable over run (abm):', h0 == sim.hash())
print('--- a Starsim-3 style module (ss.SIR) in the spec ---')
sim = ss.Sim(ss.SIR(), networks='random', n_agents=500, verbose=0, start='2020-01-01', stop='2020-03-01'); sim.init()
sp = sim.to_spec(); print(json.dumps(sp['modules'])[:900]); print(sim.hash())
show(lambda: ss.from_spec(sp))
show(lambda: ss.to_code(sp)[:100])
print('--- diff with renamed module ---')
S, I, R = ss.states(3)
a = ss.Sim(ss.Disease(S >> I @ 0.05 * I, I >> R @ ss.days(10), name='sir'), verbose=0, total_pop=1000, stop=100)
S, I, R = ss.states(3)
b = ss.Sim(ss.Disease(S >> I @ 0.05 * I, I >> R @ ss.days(10), name='flu'), verbose=0, total_pop=1000, stop=100)
ss.diff(a, b); print('hash equal:', a.hash() == b.hash())
