import json, numpy as np, sciris as sc, starsim as ss
kw = dict(verbose=0, total_pop=1000, stop=100)
def show(f):
    try: r = f(); print('NO ERROR', '' if r is None else str(r)[:200], '\n')
    except Exception as e: print(f'[{type(e).__name__}] {e}\n')
print('--- precision of a constant in a rate ---')
S, I, R = ss.states(3)
d = ss.Disease(S >> I @ 0.1 * np.cos(np.pi * I.frac) * I, I >> R @ ss.days(1/3), name='x')
sp = ss.Sim(d, **kw).to_spec()
print({t['name']:t['rate'] for t in sp['modules'][0]['transitions']})
S, I, R = ss.states(3)
d = ss.Disease(S >> I @ 0.123456789 * I, I >> R @ ss.days(10), name='x')
sp = ss.Sim(d, **kw).to_spec(); print({t['name']:t['rate'] for t in sp['modules'][0]['transitions']}, [p['value'] for p in sp['modules'][0]['pars']])
S, I, R = ss.states(3)
d = ss.Disease(S >> I @ (0.1 + 1e-9) * I, I >> R @ ss.days(10), name='x')  # literal folded into the par
sp = ss.Sim(d, **kw).to_spec(); print({t['name']:t['rate'] for t in sp['modules'][0]['transitions']}, [p['value'] for p in sp['modules'][0]['pars']])
S, I, R = ss.states(3)
d = ss.Disease(S >> I @ ss.par(0.1, name='beta') * (1 + 1e-9) * I, I >> R @ ss.days(10), name='x')
s = ss.Sim(d, **kw); sp = s.to_spec(); print({t['name']:t['rate'] for t in sp['modules'][0]['transitions']})
s2 = ss.from_spec(sp); print('hash equal after round trip with 1+1e-9 literal:', s2.hash() == s.hash(), s.hash().pars, s2.hash().pars)

print('--- E204: unknown state with declared states ---')
S, I, R = ss.states('S I R')
show(lambda: ss.Disease(S, I, R, infection=ss.transmission('S -> I', beta=0.05), recovery=ss.progression('I -> Q', dur=10)))
print('--- E606: out of bounds ---')
S, I, R = ss.states(3)
show(lambda: ss.Sim(ss.Disease(S >> I @ ss.par(0.05, bounds=[0, 0.01]) * I, I >> R @ 10, name='x'), **kw).init())
print('--- E604: par with no value ---')
S, I, R = ss.states(3)
show(lambda: ss.Sim(ss.Disease(S >> I @ ss.par(None, name='beta') * I, I >> R @ 10, name='x'), **kw).init())
print('--- E101/E102: typed arithmetic ---')
show(lambda: ss.perday(0.1) + ss.probperday(0.1))
show(lambda: ss.Sim(ss.Disease(infection=ss.transmission('S -> I', beta=0.05), recovery=ss.progression('I -> R', rate=ss.peryear(0.1) * ss.days(3))), **kw).init())
print('--- E605 formatting (code not in dict) ---')
show(lambda: ss.contacts('Narnia'))
print('--- note() drops its code ---')
ss.note('something was assumed', code='W101')
print('--- to_code with matrix contacts + connector modify + prior + likelihood ---')
S, I, R = ss.states(3)
inf = S >> I @ ss.par(0.05, bounds=[0.01, 0.1], prior=ss.lognorm_ex(0.05, 0.02), name='beta') * I
d = ss.Disease(inf, I >> R @ ss.days(10), cases=ss.outcome(0.5*inf, likelihood=ss.poisson()), name='sir')
d.stratify(age=[0, 20])
sim = ss.Sim(d, networks=ss.contacts(age=np.array([[10, 3], [3, 5]])), connectors=ss.modify('sir.pars.beta', multiply=0.5), total_pop=1000, start='2020-01-01', stop='2020-07-01', verbose=0)
sim.init(); sp = sim.to_spec()
print('prior:', sp['modules'][0]['pars'][0]['prior'], '| likelihood:', sp['modules'][0]['results'][0]['likelihood'])
print('modifiers:', json.dumps(sp['modifiers']))
print(sim.to_code())
