""" diff(), error message shape, channels """
import numpy as np, sciris as sc, starsim as ss, warnings
kw = dict(verbose=0, total_pop=1000, start='2020-01-01', stop='2020-07-01')
def sir(beta=0.05, dur=10, extra=None):
    S, I, R = ss.states(3)
    tr = dict(infection=S >> I @ ss.par(beta, name='beta') * I, recovery=I >> R @ ss.days(dur))
    return ss.Disease(**tr, name='sir')
a = ss.Sim(sir(), **kw); b = ss.Sim(sir(beta=0.08), **kw)
print('--- diff: beta changed'); ss.diff(a, b)
S, E, I, R = ss.states(4)
seir = ss.Disease(infection=S >> E @ ss.par(0.05, name='beta') * I, onset=E >> I @ ss.days(3), recovery=I >> R @ ss.days(10), name='sir')
print('--- diff: SIR vs SEIR'); ss.diff(a, ss.Sim(seir, **kw))
print('--- diff: solver + intervention'); ss.diff(a, ss.Sim(sir(), solver='abm', n_agents=500, interventions=ss.modify('sir.pars.beta', multiply=0.5, start='2020-03-01'), **kw))
print('--- diff: same model, parameter renamed')
S, I, R = ss.states(3)
c = ss.Sim(ss.Disease(infection=S >> I @ ss.par(0.05, name='transmission_rate') * I, recovery=I >> R @ ss.days(10), name='sir'), **kw)
ss.diff(a, c); print('hash equal:', a.hash() == c.hash())

print('\n=== error messages ===')
def show(f):
    try: f()
    except Exception as e: print(f'[{type(e).__name__}] {e}\n')
show(lambda: ss.Disease(infection=ss.transmission('S -> I', beta=0.05), recovery=ss.progression('I -> Q', dur=10), states=ss.states('S I R')))
show(lambda: ss.Sim(sir(), pars=dict(gamma=0.1), **kw).init())
show(lambda: ss.Sim(sir(), interventions=ss.modify('sir.pars.gamma', multiply=0.5), **kw).init())
show(lambda: ss.Sim(ss.Disease(infection=ss.transmission('S -> I', beta=0.05), recovery=ss.progression('I -> R', dur=10, rate=0.1)), **kw).init())
show(lambda: ss.Sim(sir(), approx=False, solver='ode', networks='random', n_agents=200, **kw).init())
S, I, R = ss.states(3)
show(lambda: ss.Sim(ss.Disease(S >> I @ 0.05 * I * I, I >> R @ 10, name='x'), **kw).init())
show(lambda: ss.Sim(sir(), **kw).run().run())
show(lambda: ss.Sim(sir(), pars=dict(beta=5), **kw).init())  # out of bounds? beta has no bounds here
S, I, R = ss.states(3)
show(lambda: ss.Sim(ss.Disease(S >> I @ ss.par(0.05, bounds=[0, 0.01]) * I, I >> R @ 10, name='x'), **kw).init())
print('=== CodedError attrs ===')
try: ss.error('E204', 'test')
except ss.CodedError as e: print(repr(e.code), repr(e.codename), isinstance(e, ValueError))
